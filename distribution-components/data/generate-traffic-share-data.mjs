/* generate-traffic-share-data.mjs — snapshot the frozen proto's data layer
   into a static mock for the trend / by-competitor / leaderboard carves.

   Loads the proto data chain (pulse-real-slim → entities → records → data)
   in a node vm with browser shims, then dumps the slices the Traffic Share
   fragments read. All sources are deterministic (no Math.random; the only
   Date use picks the "current week", which both oracle sides share).

   Run:  node data/generate-traffic-share-data.mjs
   Output: data/traffic-share-data.js  (window.DIST_TRAFFIC_DATA global)
*/
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const proto = join(here, '..', '..', 'analytics-dashboard-combined', 'js');

const sources = [
  'data/pulse-real-slim.js',
  'data/distribution-entities.js',
  'data/distribution-records.js',
  'data/distribution-data.js'
];

const ctx = {
  console,
  sessionStorage: { getItem: () => null, setItem: () => {}, removeItem: () => {} },
  window: {}
};
ctx.globalThis = ctx;
vm.createContext(ctx);
for (const f of sources) {
  vm.runInContext(readFileSync(join(proto, f), 'utf8'), ctx, { filename: f });
}

const D = vm.runInContext('DistributionData', ctx);

const snapshot = {
  entityLabel: D.retailerConfig.name,
  flightWeeks: D.flightWeeks,
  trafficShareMetrics: {
    summary: { share_change_pp: D.trafficShareMetrics.summary.share_change_pp },
    trend: D.trafficShareMetrics.trend,
    storeLeaderboard: D.trafficShareMetrics.storeLeaderboard
  },
  competitiveCrossover: D.competitiveCrossover,
  primaryThreats: D.primaryThreats,
  entities: { stores: D.entities.stores },
  competitorStores: D.competitorStores
};

const out = `/* traffic-share-data.js — GENERATED by data/generate-traffic-share-data.mjs.
   Static snapshot of the frozen proto's DistributionData slices consumed by
   the Traffic Share fragments (default context: all stores / current week).
   getWeekLabel carved verbatim from js/data/distribution-data.js. */
window.DIST_TRAFFIC_DATA = (function () {
  'use strict';
  var data = ${JSON.stringify(snapshot, null, 2)};

  function getWeekLabel(weekId) {
    const week = data.flightWeeks.find(w => w.id === weekId);
    if (!week) return weekId;
    const start = new Date(week.start);
    const end = new Date(week.end);
    const fmt = (d) => \`\${d.getMonth() + 1}/\${d.getDate()}\`;
    return \`\${week.label} (\${fmt(start)}-\${fmt(end)})\`;
  }

  data.getWeekLabel = getWeekLabel;
  return data;
})();
`;

writeFileSync(join(here, 'traffic-share-data.js'), out);
console.log('wrote data/traffic-share-data.js —',
  snapshot.flightWeeks.length, 'weeks,',
  snapshot.trafficShareMetrics.trend.length, 'trend points,',
  snapshot.competitiveCrossover.length, 'competitors,',
  snapshot.primaryThreats.length, 'threat brands,',
  snapshot.trafficShareMetrics.storeLeaderboard.length, 'leaderboard rows,',
  snapshot.entities.stores.length, 'stores,',
  snapshot.competitorStores.length, 'competitor stores');
